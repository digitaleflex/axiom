func TestRemoveIdempotent(t *testing.T) {
	dir := t.TempDir()
	a := &Adapter{DynamicDir: dir}
	if err := a.Configure(context.Background(), validRequest()); err != nil {
		t.Fatal(err)
	}
	if err := a.Remove(testDep); err != nil {
		t.Fatal(err)
	}
	if err := a.Remove(testDep); err != nil {
		t.Fatalf("second remove must be a no-op: %v", err)
	}
	if _, err := os.Stat(filepath.Join(dir, "axiom-"+testDep+".yml")); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("file still present: %v", err)
	}
	if err := a.Remove("bad"); !errors.Is(err, ErrInvalidDeployment) {
		t.Fatalf("err = %v, want ErrInvalidDeployment", err)
	}
}


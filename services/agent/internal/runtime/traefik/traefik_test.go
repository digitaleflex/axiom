func TestReconcileRemovesOnlyStaleAxiomFiles(t *testing.T) {
	dir := t.TempDir()
	a := &Adapter{DynamicDir: dir}
	// Two Axiom-owned configs, one active one stale.
	if err := a.Configure(context.Background(), validRequest()); err != nil {
		t.Fatal(err)
	}
	stale := validRequest()
	stale.DeploymentID = testDep2
	stale.Labels = managedLabels(testDep2)
	if err := a.Configure(context.Background(), stale); err != nil {
		t.Fatal(err)
	}
	// Foreign files that must never be touched.
	foreign := map[string]string{
		"traefik.yml":                    "entryPoints: {}\n",
		"other-dep_0123456789abcdef.yml": "x: 1\n",
		"axiom-not-a-deployment.yml":     "y: 2\n", // axiom prefix, unparseable id
		"readme.txt":                     "hello\n",
	}
	for name, body := range foreign {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}

	removed, err := a.Reconcile([]string{testDep})
	if err != nil {
		t.Fatal(err)
	}
	if len(removed) != 1 || removed[0] != "axiom-"+testDep2+".yml" {
		t.Fatalf("removed = %v, want [axiom-%s.yml]", removed, testDep2)
	}
	if _, err := os.Stat(filepath.Join(dir, "axiom-"+testDep+".yml")); err != nil {
		t.Fatalf("active config must be kept: %v", err)
	}
	for name := range foreign {
		if _, err := os.Stat(filepath.Join(dir, name)); err != nil {
			t.Fatalf("foreign file %q must be kept: %v", name, err)
		}
	}
}


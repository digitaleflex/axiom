const testDep = "dep_0123456789abcdef01234567"
const testDep2 = "dep_89abcdef0123456789abcdef"

func managedLabels(dep string) map[string]string {
	return map[string]string{
		ownership.LabelManaged:    ownership.ManagedTrue,
		ownership.LabelDeployment: dep,
	}
}

func validRequest() Request {
	return Request{
		Container:    "axiom-app-1",
		Domain:       "app.example.com",
		Port:         3000,
		TLS:          true,
		DeploymentID: testDep,
		ServerID:     "srv_test",
		Labels:       managedLabels(testDep),
	}
}

func TestConfigureGoldenTLS(t *testing.T) {
	dir := t.TempDir()
	a := &Adapter{DynamicDir: dir}
	if err := a.Configure(context.Background(), validRequest()); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(dir, "axiom-"+testDep+".yml")
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	want := "# Generated by Axiom; do not edit. Deployment " + testDep + ".\n" +
		"# Static Traefik config (entryPoints web/websecure and the ACME resolver\n" +
		"# named \"le\") is operator-managed and lives outside this file.\n" +
		"http:\n" +
		"  routers:\n" +
		"    axiom-" + testDep + "-web:\n" +
		"      rule: \"Host(`app.example.com`)\"\n" +
		"      entryPoints:\n" +
		"        - web\n" +
		"      middlewares:\n" +
		"        - axiom-" + testDep + "-redirect\n" +
		"      service: axiom-" + testDep + "\n" +
		"    axiom-" + testDep + "-websecure:\n" +
		"      rule: \"Host(`app.example.com`)\"\n" +
		"      entryPoints:\n" +
		"        - websecure\n" +
		"      service: axiom-" + testDep + "\n" +
		"      tls:\n" +
		"        certResolver: le\n" +
		"  middlewares:\n" +
		"    axiom-" + testDep + "-redirect:\n" +
		"      redirectScheme:\n" +
		"        scheme: https\n" +
		"        permanent: true\n" +
		"  services:\n" +
		"    axiom-" + testDep + ":\n" +
		"      loadBalancer:\n" +
		"        servers:\n" +
		"          - url: \"http://axiom-app-1:3000\"\n"
	if string(raw) != want {
		t.Fatalf("golden mismatch:\n--- got ---\n%s\n--- want ---\n%s", raw, want)
	}
	info, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	if info.Mode().Perm() != 0o644 {
		t.Fatalf("mode = %v, want 0644", info.Mode().Perm())
	}
}

func TestConfigureNoTLSHasNoRedirectOrCert(t *testing.T) {
	dir := t.TempDir()
	a := &Adapter{DynamicDir: dir}
	req := validRequest()
	req.TLS = false
	if err := a.Configure(context.Background(), req); err != nil {
		t.Fatal(err)
	}
	raw, err := os.ReadFile(filepath.Join(dir, "axiom-"+testDep+".yml"))
	if err != nil {
		t.Fatal(err)
	}
	// Inspect only the document body (the header comment intentionally
	// documents the operator-managed static config).
	s := string(raw)
	body := s[strings.Index(s, "http:"):]
	if strings.Contains(body, "- websecure") || strings.Contains(body, "certResolver") || strings.Contains(body, "redirectScheme") || strings.Contains(body, "tls:") {
		t.Fatalf("non-TLS config must not emit TLS constructs:\n%s", s)
	}
	if !strings.Contains(s, "axiom-"+testDep+"-web:") || !strings.Contains(s, `url: "http://axiom-app-1:3000"`) {
		t.Fatalf("missing web router or service:\n%s", s)
	}
}

func TestConfigureIdempotent(t *testing.T) {
	dir := t.TempDir()
	a := &Adapter{DynamicDir: dir}
	for i := 0; i < 3; i++ {
		if err := a.Configure(context.Background(), validRequest()); err != nil {
			t.Fatalf("configure %d: %v", i, err)
		}
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(entries) != 1 || entries[0].Name() != "axiom-"+testDep+".yml" {
		t.Fatalf("entries = %v, want exactly one axiom file", entries)
	}
	// No temp files may be left behind after atomic writes.
	for _, e := range entries {
		if strings.Contains(e.Name(), ".tmp-") {
			t.Fatalf("leftover temp file: %s", e.Name())
		}
	}
}

func TestConfigureInvalidDomainRejected(t *testing.T) {
	dir := t.TempDir()
	a := &Adapter{DynamicDir: dir}
	bad := []string{
		"", "App.example.com", "https://app.example.com", "app.example.com:443",
		"app.example.com/path", "app example.com", "-app.example.com",
		"app-.example.com", "app..example.com", "*.example.com", "app_example.com",
	}
	for _, domain := range bad {
		req := validRequest()
		req.Domain = domain
		err := a.Configure(context.Background(), req)
		if !errors.Is(err, ErrInvalidDomain) {
			t.Fatalf("domain %q: err = %v, want ErrInvalidDomain", domain, err)
		}
	}
	entries, _ := os.ReadDir(dir)
	if len(entries) != 0 {
		t.Fatalf("no file may be written for invalid domains: %v", entries)
	}
}


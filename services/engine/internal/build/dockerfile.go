package build

import (
	"fmt"
	"strings"

	"github.com/digitaleflex/axiom/services/engine/internal/runtime/presets"
	nodepresets "github.com/digitaleflex/axiom/services/engine/internal/runtime/presets/node"
)

// Dockerfile templates for source-build presets. Node/Next.js/Vite templates
// are rendered by the safe runtime presets (#121): multi-stage, pinned base
// images, lockfile-aware installs, non-root user, NODE_ENV=production. The
// Go template is refined with #122.
func dockerfileForPreset(preset, buildCommand, startCommand string, port int, outputDir string) (string, error) {
	switch preset {
	case "nextjs", "node":
		// The plan carries resolved commands, not raw facts: the package
		// manager is inferred from them and a lockfile is assumed (the
		// reproducible default; repositories without one should set
		// strategy: dockerfile).
		df, err := nodepresets.DockerfileForFacts(nodepresets.Facts{
			PackageManager: inferPackageManager(buildCommand, startCommand),
			HasBuildScript: buildCommand != "",
			HasStartScript: startCommand != "",
			Framework:      frameworkForPreset(preset),
			Port:           port,
			HasLockfile:    true,
			BuildCommand:   buildCommand,
			StartCommand:   startCommand,
		})
		if err != nil {
			return "", err
		}
		return df, nil
	case "vite":
		df, err := nodepresets.DockerfileForFacts(nodepresets.Facts{
			PackageManager: inferPackageManager(buildCommand, startCommand),
			HasBuildScript: buildCommand != "",
			Framework:      presets.FrameworkVite,
			Port:           port,
			HasLockfile:    true,
			BuildCommand:   buildCommand,
		})
		if err != nil {
			return "", err
		}
		return df, nil
	case "go":
		return fmt.Sprintf(`# Generated by Axiom for the go preset. Refined by #121.
FROM golang:1.23-alpine
WORKDIR /app
COPY . .
RUN %s
EXPOSE %d
CMD ["sh", "-c", %s]
`, shellQuote(buildCommand), port, shellQuote(startCommand)), nil
	default:
		return "", fmt.Errorf("no Dockerfile template for preset %q", preset)
	}
}

// inferPackageManager detects the package manager from the resolved commands
// (the plan carries commands, not the raw facts). Defaults to npm.
func inferPackageManager(commands ...string) string {
	for _, c := range commands {
		switch {
		case strings.HasPrefix(c, "pnpm"):
			return presets.PackageManagerPNPM
		case strings.HasPrefix(c, "yarn"):
			return presets.PackageManagerYarn
		case strings.HasPrefix(c, "bun"):
			return presets.PackageManagerBun
		case strings.HasPrefix(c, "npm"), strings.HasPrefix(c, "npx"):
			return presets.PackageManagerNPM
		}
	}
	return presets.PackageManagerNPM
}

func frameworkForPreset(preset string) string {
	if preset == "nextjs" {
		return presets.FrameworkNextJS
	}
	return ""
}

func shellQuote(s string) string {
	return `"` + strings.ReplaceAll(s, `"`, `\"`) + `"`
}

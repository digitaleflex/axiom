package build

import (
	"fmt"
	"strings"
)

// Dockerfile templates for source-build presets. These are initial templates;
// preset-specific refinements (multi-stage, caching, base image pins) arrive
// with the runtime presets (#121, #122).
func dockerfileForPreset(preset, buildCommand, startCommand string, port int, outputDir string) (string, error) {
	switch preset {
	case "nextjs", "node":
		return fmt.Sprintf(`# Generated by Axiom for the %s preset. Refined by #121.
FROM node:20-alpine
WORKDIR /app
COPY . .
RUN %s
EXPOSE %d
CMD ["sh", "-c", %s]
`, preset, shellQuote(buildCommand), port, shellQuote(startCommand)), nil
	case "vite":
		dir := outputDir
		if dir == "" {
			dir = "dist"
		}
		return fmt.Sprintf(`# Generated by Axiom for the vite preset. Refined by #121.
FROM node:20-alpine AS build
WORKDIR /app
COPY . .
RUN %s
FROM nginx:alpine
COPY --from=build /app/%s /usr/share/nginx/html
EXPOSE 80
`, shellQuote(buildCommand), dir), nil
	case "go":
		return fmt.Sprintf(`# Generated by Axiom for the go preset. Refined by #121.
FROM golang:1.23-alpine
WORKDIR /app
COPY . .
RUN %s
EXPOSE %d
CMD ["sh", "-c", %s]
`, shellQuote(buildCommand), port, shellQuote(startCommand)), nil
	default:
		return "", fmt.Errorf("no Dockerfile template for preset %q", preset)
	}
}

func shellQuote(s string) string {
	return `"` + strings.ReplaceAll(s, `"`, `\"`) + `"`
}
